-- =============================================================
-- 1D-SQL-Demo-PostgreSQL.sql   (PostgreSQL 14+)
-- =============================================================
-- The same demo as 1D-SQL-Demo-MySQL.sql, written for PostgreSQL,
-- so you can compare the syntax side by side. The precourse uses
-- MySQL 8; this file is for reference.
--
-- PostgreSQL 14 or newer is required (procedures with OUT
-- parameters were added in 14).
--
-- Run the file from top to bottom: later sections depend on the
-- tables created earlier. The whole file can be re-run safely.
--
-- Main differences from MySQL:
--   - Auto-increment:  GENERATED BY DEFAULT AS IDENTITY
--                      instead of AUTO_INCREMENT.
--   - No DELIMITER:    a procedure / function body is a string
--                      between $$ ... $$ ("dollar quoting"), with
--                      LANGUAGE plpgsql (or sql) stated explicitly.
--   - OUT parameters:  CALL passes NULL as a placeholder and the
--                      OUT value comes back as a result row; there
--                      are no @session variables.
--   - Triggers:        the body lives in a separate function that
--                      RETURNS TRIGGER; CREATE TRIGGER then calls it
--                      with EXECUTE FUNCTION.
--   - Result sets:     returned by a function (RETURNS TABLE) and
--                      queried with SELECT * FROM fn(), not by a
--                      procedure.
--   - Names:           unquoted identifiers are folded to lower
--                      case, so AverageScore is stored as
--                      averagescore.
-- =============================================================


-- =============================================================
-- SETUP
-- =============================================================
DROP TABLE IF EXISTS scores CASCADE;

CREATE TABLE scores (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_name  VARCHAR(50),
    score         INTEGER
);

INSERT INTO scores (student_name, score)
VALUES
    ('Aiden', 80),
    ('Aiden', 90),
    ('Aiden', 70),
    ('Bella', 88),
    ('Bella', 92),
    ('Chris', 75);


-- =============================================================
-- Stored Procedure with IN and OUT parameters
-- =============================================================
-- Same procedure as in MySQL. DROP PROCEDURE needs the parameter
-- types, because PostgreSQL allows several procedures with the same
-- name but different parameters (overloading).
-- AVG() of an INTEGER returns NUMERIC with many decimal places, so
-- the result is cast to NUMERIC(5,2).
DROP PROCEDURE IF EXISTS AverageScore(VARCHAR, NUMERIC);

CREATE PROCEDURE AverageScore(
    IN  p_student_name VARCHAR(50),
    OUT p_avg_score    NUMERIC(5,2)
)
LANGUAGE plpgsql
AS $$
BEGIN
    SELECT AVG(score)::NUMERIC(5,2)
    INTO p_avg_score
    FROM scores
    WHERE student_name = p_student_name;
END;
$$;

-- Look at the data first: Aiden has three scores (80, 90, 70).
--
-- Expected result:
--  id | student_name | score
-- ----+--------------+-------
--   1 | Aiden        |    80
--   2 | Aiden        |    90
--   3 | Aiden        |    70
--   4 | Bella        |    88
--   5 | Bella        |    92
--   6 | Chris        |    75
SELECT *
FROM scores
ORDER BY id;

-- Call the procedure. NULL is the placeholder for the OUT
-- parameter; the OUT value is returned as a one-row result.
-- (MySQL instead writes it into the @average session variable.)
--
-- Expected result:
--  p_avg_score
-- -------------
--        80.00
CALL AverageScore('Aiden', NULL);


-- =============================================================
-- Trigger: AFTER INSERT writes to a log table
-- =============================================================
-- CASCADE also drops objects that depend on the table, such as the
-- trigger on accounts.
DROP TABLE IF EXISTS accounts_log CASCADE;
DROP TABLE IF EXISTS accounts CASCADE;

CREATE TABLE accounts (
    account_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_name  VARCHAR(50),
    credit        NUMERIC(10,2)
);

CREATE TABLE accounts_log (
    log_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_name  VARCHAR(50),
    credit        NUMERIC(10,2),
    action_time   TIMESTAMP
);

-- These five rows are inserted BEFORE the trigger exists, so they
-- will not appear in accounts_log.
INSERT INTO accounts (account_name, credit)
VALUES
    ('Account A', 1000.00),
    ('Account B', 2500.00),
    ('Account C', 4000.00),
    ('Account D', 1500.00),
    ('Account E', 2000.00);

-- Step 1: the trigger function holds the body. In MySQL this code
-- sits directly inside CREATE TRIGGER. NEW is the row that was just
-- inserted. An AFTER trigger's return value is ignored, but a
-- trigger function must still return something; RETURN NEW is the
-- convention.
CREATE OR REPLACE FUNCTION log_account_after_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO accounts_log (account_name, credit, action_time)
    VALUES (NEW.account_name, NEW.credit, CURRENT_TIMESTAMP);

    RETURN NEW;
END;
$$;

-- Step 2: the trigger itself only says when to run the function:
-- after each row inserted into accounts.
DROP TRIGGER IF EXISTS trig_after_insert_accounts ON accounts;

CREATE TRIGGER trig_after_insert_accounts
AFTER INSERT ON accounts
FOR EACH ROW
EXECUTE FUNCTION log_account_after_insert();


-- =============================================================
-- Function that returns a result set
-- =============================================================
-- In MySQL, ShowAccounts is a procedure with a SELECT inside. In
-- PostgreSQL a procedure cannot simply return rows, so this is a
-- function that declares the columns it returns (RETURNS TABLE).
DROP FUNCTION IF EXISTS ShowAccounts();

CREATE FUNCTION ShowAccounts()
RETURNS TABLE (
    account_id    INTEGER,
    account_name  VARCHAR(50),
    credit        NUMERIC(10,2)
)
LANGUAGE sql
AS $$
    SELECT a.account_id, a.account_name, a.credit
    FROM accounts AS a
    ORDER BY a.account_id;
$$;


-- =============================================================
-- Fire the trigger
-- =============================================================
-- One INSERT statement with two rows: the trigger fires twice,
-- once per row.
INSERT INTO accounts (account_name, credit)
VALUES
    ('Account F', 5000.00),
    ('Account G', 3500.00);

-- All seven accounts are in the table.
--
-- Expected result:
--  account_id | account_name | credit
-- ------------+--------------+---------
--           1 | Account A    | 1000.00
--           2 | Account B    | 2500.00
--           3 | Account C    | 4000.00
--           4 | Account D    | 1500.00
--           5 | Account E    | 2000.00
--           6 | Account F    | 5000.00
--           7 | Account G    | 3500.00
SELECT *
FROM accounts
ORDER BY account_id;

-- A function is used like a table: SELECT * FROM fn().
-- (MySQL: CALL ShowAccounts();) Same seven rows as above.
SELECT *
FROM ShowAccounts();

-- Only F and G were logged: A to E were inserted before the
-- trigger was created. action_time is the time you ran the INSERT.
--
-- Expected result:
--  log_id | account_name | credit  | action_time
-- --------+--------------+---------+---------------------
--       1 | Account F    | 5000.00 | (current date/time)
--       2 | Account G    | 3500.00 | (current date/time)
SELECT *
FROM accounts_log
ORDER BY log_id;
